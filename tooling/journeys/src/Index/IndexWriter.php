<?php

namespace Tooling\Journeys\Index;

use Tooling\Journeys\Catalog\Catalog;
use Tooling\Journeys\Config;
use Tooling\Journeys\Coverage\Coverage;

/**
 * Renders the committed, generated artifacts. Both derive only from journey
 * YAML so they change exactly when definitions change, not on every code edit.
 */
final class IndexWriter
{
    public const INDEX_PATH = 'docs/user-journeys/INDEX.md';

    public const BASELINE_PATH = 'docs/user-journeys/coverage-baseline.json';

    public static function render(Catalog $catalog, Config $config): string
    {
        $coverage = Coverage::forCatalog($catalog);
        $lines = [
            '# User Journey Index',
            '',
            '<!-- GENERATED by `php bin/journeys index` from docs/user-journeys/journeys/*.yaml. Do not edit by hand. -->',
            '',
            'Coverage is declared per scenario in each journey file and verified by `php bin/journeys validate`',
            '(every referenced test must exist and assert something). It is scenario coverage, not line coverage.',
            '',
            '## Summary',
            '',
        ];

        $byStatus = array_count_values(array_column($coverage, 'status'));
        ksort($byStatus);
        $lines[] = '| Journeys | '.implode(' | ', array_map('ucfirst', array_map(fn ($s) => str_replace('_', ' ', $s), array_keys($byStatus)))).' |';
        $lines[] = '|---|'.str_repeat('---|', count($byStatus));
        $lines[] = '| '.count($catalog->journeys).' | '.implode(' | ', $byStatus).' |';
        $lines[] = '';

        $domains = [];
        foreach ($catalog->journeys as $journey) {
            $domains[$journey->domain][$journey->priority] = ($domains[$journey->domain][$journey->priority] ?? 0) + 1;
        }
        ksort($domains);
        $lines[] = '| Domain | Critical | High | Medium | Low |';
        $lines[] = '|---|---|---|---|---|';
        foreach ($domains as $domain => $counts) {
            $lines[] = "| {$domain} | ".implode(' | ', array_map(fn ($p) => $counts[$p] ?? 0, ['critical', 'high', 'medium', 'low'])).' |';
        }
        $lines[] = '';

        $lines[] = '## Coverage';
        $lines[] = '';
        $lines[] = '`yes` all scenarios of that kind tested · `partial` some · `no` none · `missing` no scenario declared · `n/a` not applicable';
        $lines[] = '';
        $lines[] = '| Journey | Name | Priority | Happy | Negative | Authz | Alternate | Integration | E2E | Status |';
        $lines[] = '|---|---|---|---|---|---|---|---|---|---|';
        foreach ($catalog->journeys as $id => $journey) {
            $c = $coverage[$id];
            $lines[] = sprintf(
                '| [%s](%s) | %s | %s | %s | %s | %s | %s | %s | %s | **%s** |',
                $id, substr($journey->file, strlen('docs/user-journeys/')), self::cell($journey->name), $journey->priority,
                $c['happy'], $c['negative'], $c['authorization'], $c['alternate'], $c['integration'], $c['e2e'],
                str_replace('_', ' ', $c['status']),
            );
        }
        $lines[] = '';

        $gaps = array_filter($coverage, fn ($c, $id) => $c['gaps'] !== [] && in_array($catalog->journeys[$id]->priority, ['critical', 'high'], true), ARRAY_FILTER_USE_BOTH);
        if ($gaps !== []) {
            $lines[] = '## Open gaps (critical and high priority)';
            $lines[] = '';
            foreach ($gaps as $id => $c) {
                $lines[] = "- **{$id}** — ".self::cell(implode('; ', $c['gaps']));
            }
            $lines[] = '';
        }

        $lines[] = '## Journeys by domain';
        foreach (array_keys($domains) as $domain) {
            $lines[] = '';
            $lines[] = "### {$domain}";
            $lines[] = '';
            foreach ($catalog->journeys as $id => $journey) {
                if ($journey->domain !== $domain) {
                    continue;
                }
                $lines[] = "- **{$id}** {$journey->name} _({$journey->status}, {$journey->priority})_";
                if ($journey->routes !== []) {
                    $lines[] = '  - Routes: '.implode(', ', array_map(fn ($r) => "`{$r}`", $journey->routes));
                }
                if (($tests = $journey->testFiles()) !== []) {
                    sort($tests);
                    $lines[] = '  - Tests: '.implode(', ', array_map(fn ($t) => "`{$t}`", $tests));
                }
            }
        }

        if ($config->excludedRoutes !== []) {
            $lines[] = '';
            $lines[] = '## Routes intentionally outside any journey';
            $lines[] = '';
            foreach ($config->excludedRoutes as $route => $reason) {
                $lines[] = "- `{$route}` — ".self::cell($reason);
            }
        }

        return implode("\n", $lines)."\n";
    }

    public static function renderBaseline(Catalog $catalog): string
    {
        return json_encode([
            'note' => 'Generated by `php bin/journeys index --update-baseline`. CI fails if a scenario drops below its recorded coverage.',
            'scenarios' => Coverage::baseline($catalog),
        ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES)."\n";
    }

    private static function cell(string $text): string
    {
        return str_replace(['|', "\n"], ['\\|', ' '], $text);
    }
}
